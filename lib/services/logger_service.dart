class LoggerService {
  static void info(String msg) => print('ℹ️ $msg');
  static void success(String msg) => print('✅ $msg');
  static void warning(String msg) => print('⚠️ $msg');
  static void error(String msg) => print('❌ $msg');
  static void brain(String msg) => print('🧠 $msg');
  static void memory(String msg) => print('💾 $msg');
}
